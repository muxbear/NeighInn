function pickImage(list: string[], index: number): string {
  return list[index % list.length]
}

const pic = (seed: string, _width = 800, _height = 760): string => {
  const matched = String(seed).match(/^(.*?)-(\d+)$/)
  const base = matched ? matched[1] : String(seed)
  const index = matched ? Math.max(0, Number(matched[2]) - 1) : 0

  if (base.startsWith('garden')) return UNSPLASH.lifeGarden
  if (base.startsWith('rain-garden')) return pickImage(UNSPLASH.lifeFlowers, index)
  if (base.startsWith('ginkgo')) return UNSPLASH.lifeNight
  if (base.startsWith('craft')) return pickImage(UNSPLASH.lifeKids, index)
  if (base.startsWith('corgi') || base.startsWith('cat')) return pickImage(UNSPLASH.lifePets, index)
  if (base.startsWith('dance') || base.startsWith('market')) return pickImage(UNSPLASH.lifeVolunteer, index)
  if (base.startsWith('bookcorner')) return pickImage(UNSPLASH.lifeBooks, index)
  if (base.startsWith('dress')) return UNSPLASH.lifePainting
  if (base.startsWith('coffee')) return pickImage(UNSPLASH.coffee, index)
  if (base.startsWith('dryer') || base.startsWith('switch')) return pickImage(UNSPLASH.headphones, index)
  if (base.startsWith('coat') || base.startsWith('tent') || base.startsWith('babybed')) return pickImage(UNSPLASH.decor, index)
  if (base.startsWith('desk') || base.startsWith('lego') || base.startsWith('books') || base.startsWith('vacuum') || base.startsWith('airfryer')) return pickImage(UNSPLASH.shelf, index)
  if (base.startsWith('camera')) return pickImage(UNSPLASH.camera, index)
  return pickImage(UNSPLASH.chair, index)
}

