export function createAuditProgress(itemId: string, tick: number): AuditProgress {
  const stepTitles = ['图像质量检测', '图文一致性检测', '内容合规检查', '生成质检报告']
  const completed = Math.min(tick, 4)
  const passed = tick >= 5
  const steps: AuditStep[] = stepTitles.map((title, index) => ({
    key: `step-${index + 1}`,
    title,
    status: passed ? 'DONE' : index < completed ? 'DONE' : index === completed ? 'PROCESSING' : 'PENDING',
    message: index < completed ? '已完成' : index === completed ? '检测中…' : '等待中',
  }))
  return {
    itemId,
    status: passed ? 'PASSED' : 'PROCESSING',
    progress: passed ? 100 : Math.min(96, 12 + completed * 21),
    currentText: passed ? 'AI 质检通过，等待人工复核' : `正在${stepTitles[Math.min(completed, 3)]}…`,
    steps,
    report: passed ? AUDIT_REPORT : undefined,
  }
}

