-- ============================================================================
-- 邻里小栈（NeighInn）生产库全量初始化脚本
-- ============================================================================
-- 目标数据库：neighinn_prod（PostgreSQL）
-- Alembic 版本：0013_admin_platform_user_id（执行后后续升级仍用 alembic upgrade head）
-- 初始管理员：admin（随机口令由生成脚本单独输出，首次登录强制改密）
--
-- 警告：本脚本会终止目标库现有连接并 DROP DATABASE，数据不可恢复，请先备份！
--       执行前请停止后端容器/应用，执行完成后再启动，避免迁移与业务写入并发。
-- 要求：执行账号需具备 CREATEDB 权限；若由 DBA 预建空库，可从「连接目标库」段开始执行。
--       若账号无 CREATEDB 权限，可将第 0 段替换为（保留库、清空 schema）：
--         \connect :db_name
--         DROP SCHEMA public CASCADE; CREATE SCHEMA public;
--       若集群没有 postgres 库，将 \connect postgres 改为 \connect template1。
--
-- 用法（psql）：
--   psql "postgresql://postgres@127.0.0.1:5205/postgres" \
--        -v ON_ERROR_STOP=1 -f neighinn_prod_init.sql
--   覆盖库名：追加 -v db_name=your_database
--   注意：不要加 -1/--single-transaction（CREATE DATABASE 不能在事务块内执行）。
-- ============================================================================

\set ON_ERROR_STOP on
\if :{?db_name}
\else
\set db_name neighinn_prod
\endif

-- ---------------------------------------------------------------------------
-- 0. 断开旧连接，删除并重建数据库
-- ---------------------------------------------------------------------------
\connect postgres
SELECT pg_terminate_backend(pid)
FROM pg_stat_activity
WHERE datname = :'db_name' AND pid <> pg_backend_pid();
DROP DATABASE IF EXISTS :"db_name";
CREATE DATABASE :"db_name" WITH ENCODING 'UTF8' TEMPLATE template0;
\connect :db_name

SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;
SET search_path = public;
SET TIME ZONE 'UTC';
-- 可选：统一数据库默认时区（应用连接串已通过 options=-c timezone=UTC 强制）：
-- ALTER DATABASE :"db_name" SET timezone TO 'UTC';

